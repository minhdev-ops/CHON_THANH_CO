import { ref } from 'vue'

export type Locale = 'vi' | 'en' | 'zh'

const STORAGE_KEY = 'ct-locale'

export const localeNames: Record<Locale, string> = {
  vi: 'Tiếng Việt',
  en: 'English',
  zh: '中文',
}

function readInitial(): Locale {
  if (typeof window === 'undefined') return 'vi'
  const saved = window.localStorage.getItem(STORAGE_KEY)
  return saved === 'en' || saved === 'zh' ? saved : 'vi'
}

export const locale = ref<Locale>(readInitial())

export function setLocale(l: Locale) {
  locale.value = l
  if (typeof document !== 'undefined') document.documentElement.lang = l
  if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, l)
}

if (typeof document !== 'undefined') {
  document.documentElement.lang = locale.value
}

export function t(key: string, data?: Record<string, string | number>): string {
  const dict = dictionaries[locale.value] ?? dictionaries.vi
  let text = dict[key] ?? dictionaries.vi[key] ?? key
  if (data) {
    for (const [k, v] of Object.entries(data)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return text
}

