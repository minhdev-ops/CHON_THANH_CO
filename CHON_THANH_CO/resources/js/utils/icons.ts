export function faIcon(name?: string | null): string {
    if (!name) return 'fa-circle'
    const key = name.trim()
    if (!key) return 'fa-circle'
    if (key.startsWith('fa-')) return key
    return ICON_MAP[key] ?? 'fa-circle'
}
